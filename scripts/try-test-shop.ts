import { writeFile } from "node:fs/promises";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import type { ClauseReport } from "../src/scan/map.js";
import { compare, loadExpected, serveShop, type Comparison } from "../test/testShop.js";

/**
 * End-to-end run through the real MCP server, the way an assistant would use it:
 *
 *   npm run try              # the local test shop only, no network
 *   npm run try -- --w3c     # also W3C's Before and After Demonstration site
 *
 * Writes examples/RESULTS.md. Exits 1 if the test shop does not match
 * examples/test-shop/expected.json.
 */

const withW3c = process.argv.includes("--w3c");
const OUT = new URL("../examples/RESULTS.md", import.meta.url);

/** W3C WAI's demo site: the same four pages built inaccessibly ("before") and fixed ("after"). */
const W3C_BAD = "https://www.w3.org/WAI/demos/bad";
const W3C_PAGES = ["home", "news", "tickets", "survey"];

type Scan = ClauseReport & { caveat: string };

const shop = await serveShop();
const transport = new StdioClientTransport({ command: "npx", args: ["tsx", "src/mcp/bin.ts"], stderr: "inherit" });
const client = new Client({ name: "eaa-cite-try", version: "0" });
await client.connect(transport);

async function call<T>(name: string, args: Record<string, unknown>): Promise<T> {
  const result = (await client.callTool({ name, arguments: args })) as { isError?: boolean; content: { text: string }[] };
  if (result.isError) throw new Error(`${name}: ${result.content[0]?.text}`);
  return JSON.parse(result.content[0]!.text) as T;
}

const lines: string[] = [];
const out = (line = ""): void => {
  lines.push(line);
};

// ---- Test shop -------------------------------------------------------------

const comparisons: { c: Comparison; scan: Scan }[] = [];
for (const page of await loadExpected()) {
  const scan = await call<Scan>("scan_url", { url: `${shop.origin}/${page.path}` });
  comparisons.push({ c: compare(page, scan), scan });
}

const planted = comparisons.reduce((n, { c }) => n + c.expectedRules.length, 0);
const found = comparisons.reduce((n, { c }) => n + c.expectedRules.filter((r) => r.found).length, 0);
const unexpected = comparisons.reduce((n, { c }) => n + c.unexpected.length, 0);
const hidden = comparisons.reduce((n, { c }) => n + c.notDetectable.length, 0);
const allOk = comparisons.every(({ c }) => c.ok);

out("# Test results");
out();
out(`Generated by \`npm run try${withW3c ? " -- --w3c" : ""}\` on ${new Date().toISOString().slice(0, 10)}. Every scan below went through the MCP server's \`scan_url\` tool over stdio.`);
out();
out("## Test shop");
out();
out("Five pages in [`examples/test-shop/`](test-shop/), served over HTTP on 127.0.0.1. Each defect is marked with a `PLANTED` comment in the page, and [`expected.json`](test-shop/expected.json) says what the scan should report. It was written before the first scan.");
out();
out(`${allOk ? "**Result: matches expected.json.**" : "**Result: DOES NOT match expected.json.**"} ${found} of ${planted} planted axe-detectable defects found under the expected EN clauses, ${unexpected} failures nobody planted. ${hidden} planted defects axe has no rule for: none reported as failing, all listed as not checked by axe.`);
out();
out("| Page | Planted, found | Unexpected | Needs review | Not checked by axe |");
out("|---|---|---|---|---|");
for (const { c, scan } of comparisons) {
  const f = c.expectedRules.filter((r) => r.found).length;
  const review = scan.needsReview.map((r) => r.enClause).join(", ") || "none";
  out(`| \`${c.page.path}\` (${c.page.template}) | ${f} / ${c.expectedRules.length} | ${c.unexpected.length} | ${review} | ${scan.summary.notCheckedByAxe} of ${scan.summary.ofCriteria} |`);
}

for (const { c, scan } of comparisons) {
  out();
  out(`### \`${c.page.path}\``);
  out();
  if (scan.failing.length === 0) {
    out("No failures in clause 9.");
  } else {
    out("| EN clause | Criterion | axe rule | Instances | Planted? |");
    out("|---|---|---|---|---|");
    for (const criterion of scan.failing) {
      for (const rule of criterion.rules) {
        const expected = c.page.failing[rule.ruleId]?.includes(criterion.enClause);
        out(`| ${criterion.enClause} | ${criterion.name} | \`${rule.ruleId}\` | ${rule.instances} | ${expected ? "yes" : "**no**"} |`);
      }
    }
  }
  for (const r of c.expectedRules.filter((r) => !r.found)) out(`\nMissed: \`${r.ruleId}\` expected under ${r.clauses.join(", ")}.`);
  if (scan.needsReview.length) {
    out();
    out(`Needs review: ${scan.needsReview.map((r) => `${r.enClause} ${r.name} (\`${r.rules.map((x) => x.ruleId).join("`, `")}\`)${c.page.needsReview.includes(r.enClause) ? "" : ", not planted"}`).join("; ")}.`);
  }
  if (c.notDetectable.length) {
    out();
    out("Planted, and axe has no rule for it:");
    for (const d of c.notDetectable) {
      out(`- ${d.wcagRef}: ${d.what}. ${d.wronglyFailing ? "**Reported as failing.**" : d.reportedAsNotChecked ? "Listed under not checked by axe." : "Not listed as failing, but some axe rule touched the criterion."}`);
    }
  }
}

// ---- W3C BAD ---------------------------------------------------------------

if (withW3c) {
  out();
  out("## W3C Before and After Demonstration");
  out();
  out(`W3C WAI publishes the same four pages twice: built with known barriers ([before](${W3C_BAD}/before/home.html)) and repaired ([after](${W3C_BAD}/after/home.html)). There is no expected.json for these; the check is that "after" fails far less than "before", and what remains is worth reading.`);
  out();
  out("| Page | Before: failing criteria | After: failing criteria | Before: instances | After: instances |");
  out("|---|---|---|---|---|");
  const details: string[] = [];
  for (const name of W3C_PAGES) {
    const [before, after] = [
      await call<Scan>("scan_url", { url: `${W3C_BAD}/before/${name}.html` }),
      await call<Scan>("scan_url", { url: `${W3C_BAD}/after/${name}.html` }),
    ];
    const instances = (s: Scan): number => s.failing.reduce((n, c) => n + c.rules.reduce((m, r) => m + r.instances, 0), 0);
    out(`| ${name} | ${before.summary.failing} | ${after.summary.failing} | ${instances(before)} | ${instances(after)} |`);
    const list = (s: Scan): string =>
      s.failing.map((c) => `${c.enClause} ${c.name} (\`${c.rules.map((r) => r.ruleId).join("`, `")}\`)`).join("; ") || "none";
    details.push(`- **${name}**, before: ${list(before)}`, `- **${name}**, after: ${list(after)}`);
  }
  out();
  out(details.join("\n"));
}

// ---- Legal context ---------------------------------------------------------

out();
out("## What the law says about it");
out();
out("The same server answers the legal questions. From `compare_jurisdictions { claim: \"penalties\" }`:");
out();
type Row = { jurisdiction: string; value: { maxFine: number | null; currency: string | null }; citations: { pinpoint: string; source: { url: string } }[] };
const penalties = await call<{ rows: Row[] }>("compare_jurisdictions", { claim: "penalties" });
out("| Jurisdiction | Highest fine stated | Where |");
out("|---|---|---|");
for (const row of penalties.rows) {
  const amount = row.value.maxFine === null ? "none in the text" : `${row.value.maxFine.toLocaleString("en")} ${row.value.currency}`;
  const last = row.citations[row.citations.length - 1]!;
  out(`| ${row.jurisdiction} | ${amount} | [${last.pinpoint}](${last.source.url}) |`);
}
out();
const statement = await call<{ sentence: string; mayClaimPresumptionOfConformity: boolean }>("conformance_statement", { country: "DE" });
out("And from `conformance_statement { country: \"DE\" }`, the sentence a report on any of these pages could print:");
out();
out(`> ${statement.sentence}`);
out();
out(`\`mayClaimPresumptionOfConformity\`: ${statement.mayClaimPresumptionOfConformity}`);

await client.close();
await shop.close();
await writeFile(OUT, lines.join("\n") + "\n");
console.log(lines.join("\n"));
if (!allOk) process.exit(1);
